"""
train_model.py
---------------
Trains a gesture classifier on the landmark CSV produced by
data_collection.py, and saves the fitted model + label encoder to disk.

Run:
    python -m src.train_model --language ASL

The classifier is a RandomForest by default (fast, robust on small tabular
landmark datasets, no GPU needed) but you can switch to an MLP via --model.
"""

import argparse
import json
import os
from datetime import datetime, timezone

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import LabelEncoder

from src.config import dataset_csv_path, label_encoder_path, metadata_path, model_path


def load_dataset(csv_path: str):
    if not os.path.exists(csv_path):
        raise FileNotFoundError(
            f"No dataset found at {csv_path}. Run data_collection.py first."
        )
    df = pd.read_csv(csv_path)
    if df.empty:
        raise ValueError(f"Dataset at {csv_path} is empty.")
    X = df.drop(columns=["label"]).values.astype(np.float32)
    y = df["label"].values
    return X, y


def build_model(kind: str):
    if kind == "rf":
        return RandomForestClassifier(
            n_estimators=200,
            max_depth=20,
            min_samples_leaf=2,
            n_jobs=-1,
            random_state=42,
        )
    if kind == "mlp":
        return MLPClassifier(
            hidden_layer_sizes=(128, 64),
            max_iter=800,
            random_state=42,
        )
    raise ValueError(f"Unknown model kind: {kind}")


def train(language: str, model_kind: str = "rf", test_size: float = 0.2, data_source: str = "real"):
    csv_path = dataset_csv_path(language)
    X, y_raw = load_dataset(csv_path)

    encoder = LabelEncoder()
    y = encoder.fit_transform(y_raw)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=42, stratify=y if len(set(y)) > 1 else None
    )

    clf = build_model(model_kind)
    clf.fit(X_train, y_train)

    y_pred = clf.predict(X_test)
    acc = accuracy_score(y_test, y_pred)

    is_synthetic = (data_source == "synthetic")
    accuracy_label = (
        f"{acc * 100:.2f}% [SYNTHETIC — not indicative of real-world performance]"
        if is_synthetic else f"{acc * 100:.2f}%"
    )
    print(f"[RESULT] Validation accuracy: {accuracy_label}")
    print(classification_report(y_test, y_pred, target_names=[str(c) for c in encoder.classes_]))

    if acc == 1.0 and is_synthetic:
        print("\n" + "="*80)
        print("WARNING: 100% validation accuracy detected.")
        print("If you are using the SYNTHETIC dataset generated by generate_synthetic_data.py,")
        print("this accuracy is not indicative of real-world sign recognition performance.")
        print("It simply means the trivial synthetic clusters were separated.")
        print("="*80 + "\n")

    joblib.dump(clf, model_path(language))
    joblib.dump(encoder, label_encoder_path(language))
    print(f"[SAVED] Model  -> {model_path(language)}")
    print(f"[SAVED] Labels -> {label_encoder_path(language)}")

    # Write metadata sidecar
    counts_per_label = {label: int((y_raw == label).sum()) for label in encoder.classes_}
    meta = {
        "language": language,
        "data_source": data_source,
        "synthetic": is_synthetic,
        "model_kind": model_kind,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "num_classes": len(encoder.classes_),
        "total_samples": len(X),
        "train_samples": len(X_train),
        "test_samples": len(X_test),
        "validation_accuracy": round(acc, 4),
        "samples_per_label": counts_per_label,
    }
    mpath = metadata_path(language)
    with open(mpath, "w") as f:
        json.dump(meta, f, indent=2)
    print(f"[SAVED] Metadata -> {mpath}")

    return clf, encoder, acc


def parse_args():
    parser = argparse.ArgumentParser(description="Train the SignBridge gesture classifier.")
    parser.add_argument("--language", default="ASL", choices=["ASL", "ISL"])
    parser.add_argument("--model", default="rf", choices=["rf", "mlp"])
    parser.add_argument("--test-size", type=float, default=0.2)
    parser.add_argument(
        "--source", default="real", choices=["real", "synthetic", "public_dataset"],
        help="Data source label written to metadata sidecar. Use 'synthetic' for generated data, 'public_dataset' for imported image folders, 'real' for webcam.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    train(args.language, args.model, args.test_size, data_source=args.source)
